import React from 'react';
import { Icon } from './Icon';

type CompatProps = React.HTMLAttributes<HTMLSpanElement> & {
  size?: number | string;
  color?: string;
  strokeWidth?: number;
  absoluteStrokeWidth?: boolean;
};

const materialIcon = (symbol: string, label: string) => {
  const Component = React.forwardRef<HTMLSpanElement, CompatProps>(({
    size = 24, color, style, strokeWidth: _strokeWidth,
    absoluteStrokeWidth: _absoluteStrokeWidth, ...props
  }, ref) => (
    <Icon ref={ref} name={symbol} size={size} style={{ ...style, ...(color ? { color } : {}) }} {...props} />
  ));
  Component.displayName = `GoogleMaterial${label}`;
  return Component;
};

